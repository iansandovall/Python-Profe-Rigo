cadena = "Este es un ejemplo de Substring (Devanado de Cadenas)"

print(len(cadena)) #Devuelve la longitud de la cadena
print(cadena[0]) #Acceder al primer caracter o a la primera posición
print(cadena[52]) #Acceder al último caracter

print(cadena[-2]) #Acceder a las posiciones en orden inverso (de derecha a izquierda)

print(cadena[0:4]) #Devanado de cadenas
print(cadena[-8:-1]) #Devanado de cadenas

print(cadena[ :4]) #Devanado de cadenas desde donde comienza
print(cadena[10: ]) #Devanado de cadenas desde índice hasta donde termina

